import { CONVERSATION_PDF_FOOTER, CONVERSATION_PDF_OPTIONS, renderConversation } from './conversation';
import type { TranscriptEntry } from '../../ai/conversation-transcript';

const DISCLAIMER = 'Generated by Daubert. AI output; verify before relying on it.';

const entries: TranscriptEntry[] = [
  { kind: 'user', at: '2026-09-01T10:00:00.000Z', text: 'Look at this\nsecond line', attachments: ['Affidavit.pdf'] },
  { kind: 'action', at: '2026-09-01T10:00:05.000Z', label: 'Read data room file', target: 'Affidavit.pdf', failed: false },
  { kind: 'action', at: '2026-09-01T10:00:06.000Z', label: 'Web search', target: 'acme corp', failed: true },
  { kind: 'assistant', at: '2026-09-01T10:00:10.000Z', markdown: '## Findings\n\n- one\n- **two**' },
];

const base = {
  title: 'Wallet review',
  caseName: 'Acme Case',
  ownerName: 'Jane Doe',
  exportedAt: '2026-10-11T12:00:00.000Z',
  firstMessageAt: '2026-09-01T10:00:00.000Z',
  entries,
  truncatedByRetention: false,
  format: 'pdf' as const,
};

describe('renderConversation', () => {
  it('renders a sample transcript', () => {
    expect(renderConversation(base)).toMatchSnapshot();
  });

  it('renders user text escaped with line breaks preserved', () => {
    const html = renderConversation({
      ...base,
      entries: [{ kind: 'user', at: base.exportedAt, text: '<b>hi</b>\nthere', attachments: ['<i>x</i>.pdf'] }],
    });
    expect(html).not.toContain('<b>hi</b>');
    expect(html).toContain('&lt;b&gt;hi&lt;/b&gt;');
    expect(html).toContain('&lt;i&gt;x&lt;/i&gt;.pdf');
    expect(html).toMatch(/hi&lt;\/b&gt;<br\s*\/?>\s*there/);
  });

  it('strips scripts from assistant markdown', () => {
    const html = renderConversation({
      ...base,
      entries: [{ kind: 'assistant', at: base.exportedAt, markdown: 'ok <script>alert(1)</script> **bold**' }],
    });
    expect(html).not.toContain('<script');
    expect(html).not.toContain('alert(1)');
    expect(html).toContain('<strong>bold</strong>');
  });

  it('escapes title, case name, owner name and action text', () => {
    const html = renderConversation({
      ...base,
      title: '<img src=x onerror=1>',
      caseName: '<u>case</u>',
      ownerName: '<s>owner</s>',
      entries: [{ kind: 'action', at: base.exportedAt, label: '<l>', target: '<t>', failed: false }],
    });
    expect(html).not.toContain('<img src=x');
    expect(html).not.toContain('<u>case</u>');
    expect(html).not.toContain('<s>owner</s>');
    expect(html).not.toContain('<l>');
    expect(html).not.toContain('<t>');
    expect(html).toContain('&lt;img src=x onerror=1&gt;');
  });

  it('falls back to an untitled heading', () => {
    expect(renderConversation({ ...base, title: null })).toContain('Untitled conversation');
  });

  it('shows the retention line only when flagged', () => {
    const line = 'Messages older than 30 days were deleted under the chat retention policy and are not included.';
    expect(renderConversation(base)).not.toContain(line);
    expect(renderConversation({ ...base, truncatedByRetention: true })).toContain(line);
  });

  it('marks failed actions', () => {
    const html = renderConversation(base);
    expect(html).toContain('Read data room file: Affidavit.pdf');
    expect(html).toContain('Web search: acme corp (failed)');
  });

  it('puts the disclaimer in the body for docx only', () => {
    expect(renderConversation({ ...base, format: 'docx' })).toContain(`<p class="disclaimer">${DISCLAIMER}</p>`);
    expect(renderConversation(base)).not.toContain(DISCLAIMER);
  });

  it('exports a static PDF footer and options', () => {
    expect(CONVERSATION_PDF_FOOTER).toContain(DISCLAIMER);
    expect(CONVERSATION_PDF_OPTIONS).toMatchObject({
      displayHeaderFooter: true,
      footerTemplate: CONVERSATION_PDF_FOOTER,
      timeout: 120_000,
    });
    expect(CONVERSATION_PDF_OPTIONS.margin.bottom).toBe('20mm');
  });
});
