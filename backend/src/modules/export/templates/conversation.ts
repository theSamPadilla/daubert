import { marked } from 'marked';
import type { TranscriptEntry } from '../../ai/conversation-transcript';
import { BASE_STYLES, CSP_META } from './styles';
import { CHAT_RETENTION_DAYS } from '../../ai/retention/chat-retention.service';
import { escapeHtml, sanitizeHtml } from './util';

export const CONVERSATION_DISCLAIMER = 'Generated by Daubert. AI output; verify before relying on it.';

export const CONVERSATION_RETENTION_NOTE =
  `Messages older than ${CHAT_RETENTION_DAYS} days were deleted under the chat retention policy and are not included.`;

/** Static Chromium footer template (PDF only). */
export const CONVERSATION_PDF_FOOTER = `<div style="width:100%;font-size:8px;color:#6b7280;text-align:center;font-family:Arial,sans-serif;">${CONVERSATION_DISCLAIMER}</div>`;

/** Options to pass to ExportService.htmlToPdf for a conversation PDF. */
export const CONVERSATION_PDF_OPTIONS = {
  displayHeaderFooter: true,
  footerTemplate: CONVERSATION_PDF_FOOTER,
  margin: { top: '20mm', bottom: '20mm', left: '15mm', right: '15mm' },
  timeout: 120_000,
} as const;

export interface ConversationRenderInput {
  title: string | null;
  caseName: string;
  ownerName: string;
  exportedAt: string;
  firstMessageAt: string | null;
  entries: TranscriptEntry[];
  truncatedByRetention: boolean;
  /** docx has no footer support, so the disclaimer is rendered in the body. */
  format: 'pdf' | 'docx';
}

const CONVERSATION_STYLES = `
  .meta { color: #4b5563; font-size: 10pt; margin-bottom: 12pt; }
  .meta div { margin-bottom: 2pt; }
  .retention { font-size: 10pt; font-style: italic; color: #92400e; margin-bottom: 12pt; }
  .turn { margin-bottom: 14pt; }
  .turn-head { font-size: 9pt; color: #6b7280; margin-bottom: 4pt; }
  .turn-head .who { font-weight: 700; color: #111; text-transform: uppercase; letter-spacing: 0.04em; }
  .turn.user .body { border-left: 3px solid #d1d5db; padding-left: 10pt; }
  .attachments { font-size: 10pt; color: #4b5563; margin-top: 4pt; }
  .actions { margin: 0 0 14pt 0; }
  .action { font-size: 9pt; color: #6b7280; margin: 0 0 2pt 0; }
  .disclaimer { margin-top: 24pt; font-size: 9pt; color: #6b7280; text-align: center; }
`;

function formatTime(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
}

function formatDate(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toISOString().slice(0, 10);
}

function renderEntries(entries: TranscriptEntry[]): string {
  const out: string[] = [];
  let actions: string[] = [];
  const flush = () => {
    if (actions.length) out.push(`<div class="actions">${actions.join('')}</div>`);
    actions = [];
  };
  for (const e of entries) {
    if (e.kind === 'action') {
      const target = e.target ? `: ${escapeHtml(e.target)}` : '';
      const failed = e.failed ? ' (failed)' : '';
      actions.push(`<p class="action">${escapeHtml(e.label)}${target}${failed}</p>`);
      continue;
    }
    flush();
    if (e.kind === 'user') {
      const text = e.text ? `<p>${escapeHtml(e.text).replace(/\r?\n/g, '<br>')}</p>` : '';
      const atts = e.attachments.length
        ? `<p class="attachments">Attachments: ${e.attachments.map(escapeHtml).join(', ')}</p>`
        : '';
      out.push(
        `<div class="turn user"><div class="turn-head"><span class="who">You</span> ${formatTime(e.at)}</div><div class="body">${text}${atts}</div></div>`,
      );
    } else {
      const html = sanitizeHtml(marked.parse(e.markdown, { async: false }) as string);
      out.push(
        `<div class="turn assistant"><div class="turn-head"><span class="who">Assistant</span> ${formatTime(e.at)}</div><div class="body">${html}</div></div>`,
      );
    }
  }
  flush();
  return out.join('\n');
}

export function renderConversation(input: ConversationRenderInput): string {
  const title = input.title?.trim() || 'Untitled conversation';
  const last = input.entries.length ? input.entries[input.entries.length - 1].at : null;
  const first = input.firstMessageAt;
  let range = '';
  if (first && last) {
    const a = formatDate(first);
    const b = formatDate(last);
    range = a === b ? a : `${a} to ${b}`;
  } else if (first) {
    range = formatDate(first);
  }
  const meta = [
    `<div>Case: ${escapeHtml(input.caseName)}</div>`,
    `<div>Exported by: ${escapeHtml(input.ownerName)}</div>`,
    `<div>Exported at: ${formatTime(input.exportedAt)}</div>`,
    range ? `<div>Date range: ${range}</div>` : '',
  ].join('');
  const retention = input.truncatedByRetention ? `<p class="retention">${CONVERSATION_RETENTION_NOTE}</p>` : '';
  const closing = input.format === 'docx' ? `<p class="disclaimer">${CONVERSATION_DISCLAIMER}</p>` : '';

  return `<!DOCTYPE html>
<html><head><meta charset="utf-8">${CSP_META}<title>${escapeHtml(title)}</title>
<style>${BASE_STYLES}${CONVERSATION_STYLES}</style>
</head><body>
<h1>${escapeHtml(title)}</h1>
<div class="meta">${meta}</div>
${retention}
${renderEntries(input.entries)}
${closing}
</body></html>`;
}
